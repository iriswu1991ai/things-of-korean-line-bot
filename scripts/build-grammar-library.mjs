const records = Object.entries(levels).flatMap(([level, patterns]) =>
  patterns.map((pattern, index) => ({
    id: `g${level}-${String(index + 1).padStart(2, "0")}`,
    level: Number(level),
    pattern
  }))
);

const duplicatePatterns = records
  .map((item) => item.pattern)
  .filter((pattern, index, values) => values.indexOf(pattern) !== index);

if (duplicatePatterns.length) {
  throw new Error(`Duplicate grammar patterns: ${duplicatePatterns.join(", ")}`);
}

if (records.length !== 180) {
  throw new Error(`Expected 180 grammar patterns, got ${records.length}`);
}

await mkdir("data", { recursive: true });
await writeFile("data/topik-grammar.json", `${JSON.stringify(records, null, 2)}\n`);
console.log(`Generated ${records.length} grammar patterns`);
